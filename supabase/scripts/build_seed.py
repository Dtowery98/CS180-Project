"""Build supabase/seed.sql from the UCR schedule CSV export.

Usage (from the repo root):
    python3 supabase/scripts/build_seed.py "/path/to/UCR_Fall_2026_data"

Then load it into your local database with:
    npx supabase db reset
"""
import csv
import sys
from pathlib import Path

BATCH = 500


def read(folder, name):
    path = next(Path(folder).glob(f"*_{name}.csv"))
    with open(path, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def lit(value):
    """Turn a Python value into a SQL literal. Blank / TBA -> NULL."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return "array[" + ",".join(lit(v) for v in value) + "]::text[]" if value else "null"
    value = str(value).strip()
    if value == "" or value.upper() == "TBA":
        return "null"
    return "'" + value.replace("'", "''") + "'"


def num(value):
    try:
        if not value.strip():
            return "null"
        f = float(value)
        return str(int(f)) if f.is_integer() else str(f)
    except ValueError:
        return "null"


def boolean(value):
    v = value.strip().lower()
    return "true" if v == "true" else "false" if v == "false" else "null"


def inserts(table, columns, rows):
    out = []
    for i in range(0, len(rows), BATCH):
        chunk = rows[i:i + BATCH]
        out.append(f"insert into public.{table} ({', '.join(columns)}) values\n"
                   + ",\n".join("(" + ", ".join(r) + ")" for r in chunk) + ";\n")
    return out


def main(folder):
    courses = read(folder, "courses")
    sections = read(folder, "sections")
    meetings = read(folder, "meetings")

    course_rows = [[
        lit(c["Course"]), lit(c["subject"]), lit(c["courseNumber"]),
        lit(c["Catalog title"] or c["courseTitle"]), lit(c["College"]), lit(c["Department"]),
        num(c["creditHourLow"]), num(c["creditHourHigh"] or c["creditHourLow"]),
        lit(c["Full course description"]),
    ] for c in courses]

    section_rows = [[
        lit(s["Term code"]), lit(s["CRN"]), lit(s["Course"]), lit(s["Section"]),
        lit(s["Class type"]), lit(s["Instructors"]),
        num(s["Minimum units"]), num(s["Maximum units"]),
        num(s["Capacity"]), num(s["Enrollment"]), num(s["Seats available"]),
        lit(s["Delivery method"]), boolean(s["Linked section flag"]), lit(s["Link identifier"]),
    ] for s in sections]

    day_cols = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
    meeting_rows = [[
        lit(m["Term code"]), lit(m["CRN"]), num(m["Meeting number"]), lit(m["Meeting type"]),
        lit([d for d in day_cols if m[d].strip().lower() == "true"]),
        lit(m["Start time"]), lit(m["End time"]), lit(m["Start date"]), lit(m["End date"]),
        lit(m["Building"]), lit(m["Room"]),
    ] for m in meetings]

    parts = ["-- Generated by supabase/scripts/build_seed.py. Do not edit by hand.\n",
             f"-- {len(courses)} courses, {len(sections)} sections, {len(meetings)} meetings\n\n"]
    parts += inserts("courses", ["course_code", "subject", "course_number", "title", "college",
                                 "department", "units_min", "units_max", "description"], course_rows)
    parts += inserts("sections", ["term_code", "crn", "course_code", "section", "class_type",
                                  "instructors", "units_min", "units_max", "capacity", "enrollment",
                                  "seats_available", "delivery_method", "is_linked", "link_identifier"],
                     section_rows)
    parts += inserts("meetings", ["term_code", "crn", "meeting_number", "meeting_type", "days",
                                  "start_time", "end_time", "start_date", "end_date", "building", "room"],
                     meeting_rows)

    out = Path(__file__).resolve().parent.parent / "seed.sql"
    out.write_text("".join(parts), encoding="utf-8")
    print(f"Wrote {out}: {len(courses)} courses, {len(sections)} sections, {len(meetings)} meetings")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
